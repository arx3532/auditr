'use client'

import { ChevronDownIcon } from 'lucide-react'
import { useState } from 'react'

import { cn } from '@/lib/utils'

const faqs = [
  {
    question: 'What is this?',
    answer:
      'This is a portfolio demonstration project showing how an AI agent can interpret natural language billing instructions, prepare an invoice draft, and require user confirmation before executing any write.',
  },
  {
    question: 'Is it real accounting software?',
    answer:
      'No. It is a technical prototype and architecture demo built to demonstrate deterministic guardrails around LLM agents. It is not an enterprise ERP or full accounting platform.',
  },
  {
    question: 'Does it give tax advice?',
    answer:
      'No. GST and TDS formulas are calculated by hardcoded, tested Python functions for demonstration purposes only. Nothing generated by this application constitutes tax, legal, or accounting advice.',
  },
  {
    question: 'Is my data safe?',
    answer:
      'Sensitive identifiers like account numbers and tax IDs are masked before prompts reach external language models. However, because this is an unmonitored portfolio sandbox, please use synthetic test data only.',
  },
  {
    question: 'Is the code available?',
    answer:
      'Yes. The entire codebase for both the Next.js frontend and the FastAPI/LangGraph backend is open source and available on GitHub.',
  },
  {
    question: 'Why does it ask me to confirm?',
    answer:
      'Language models can hallucinate or misinterpret user intent. Having a mandatory human-in-the-loop approval gate ensures that no invoice is created or issued without explicit verification.',
  },
]

export function FAQSection() {
  const [openIndex, setOpenIndex] = useState<number | null>(null)

  const toggle = (index: number) => {
    setOpenIndex(openIndex === index ? null : index)
  }

  return (
    <section id="faq" className="border-t border-border px-4 py-16 sm:px-6 sm:py-24 lg:px-8">
      <div className="mx-auto max-w-3xl">
        <div className="text-center">
          <h2 className="text-xs font-semibold uppercase tracking-wider text-primary">Common Questions</h2>
          <p className="mt-2 text-2xl font-bold tracking-tight text-foreground sm:text-3xl">
            Frequently asked questions
          </p>
          <p className="mt-3 text-sm text-muted-foreground">
            Clear, honest answers about what this project is and what it is not.
          </p>
        </div>

        <div className="mt-12 divide-y divide-border rounded-lg border border-border bg-card">
          {faqs.map((faq, idx) => {
            const isOpen = openIndex === idx
            return (
              <div
                key={faq.question}
                className={cn('overflow-hidden transition-colors', isOpen && 'bg-secondary/40')}
              >
                <button
                  type="button"
                  onClick={() => toggle(idx)}
                  className="flex w-full items-center justify-between p-4 sm:p-5 text-left text-sm font-semibold text-foreground transition-colors hover:bg-muted/50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary focus-visible:ring-offset-2"
                  aria-expanded={isOpen}
                  aria-controls={`faq-answer-${idx}`}
                  id={`faq-question-${idx}`}
                >
                  <span>{faq.question}</span>
                  <ChevronDownIcon
                    className={cn(
                      'size-4 shrink-0 text-accent transition-transform duration-200',
                      isOpen && 'rotate-180',
                    )}
                    aria-hidden="true"
                  />
                </button>
                {isOpen && (
                  <div
                    id={`faq-answer-${idx}`}
                    role="region"
                    aria-labelledby={`faq-question-${idx}`}
                    className="px-4 pb-4 sm:px-5 sm:pb-5 text-xs sm:text-sm text-muted-foreground leading-relaxed"
                  >
                    <p>{faq.answer}</p>
                  </div>
                )}
              </div>
            )
          })}
        </div>
      </div>
    </section>
  )
}
